"""Synthetic data generators, for tests and the offline demo only.

Nothing here is market data. The generators let the test suite run without
network access and check estimators against known true parameters. The
report pipeline never imports this module.

garch_series       GARCH(1,1) / GJR-GARCH returns with known parameters
factor_panel       asset returns driven by known factor betas
synthetic_market   asset and factor-proxy prices shaped like ``download_prices`` output
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from .. import TRADING_DAYS

SYNTHETIC_WARNING = (
    "SYNTHETIC DATA: generated by risklib.data.synthetic, not real market data"
)


def garch_series(
    n: int,
    omega: float = 1e-6,
    alpha: float = 0.08,
    beta: float = 0.90,
    gamma: float = 0.0,
    mu: float = 0.0,
    nu: float | None = None,
    seed: int | None = 0,
    burn: int = 500,
) -> tuple[np.ndarray, np.ndarray]:
    """Simulate a (GJR-)GARCH(1,1) return series with known parameters.

    sigma2_t = omega + (alpha + gamma * 1[e_{t-1} < 0]) e_{t-1}^2 + beta sigma2_{t-1}

    Parameters
    ----------
    nu : float or None
        If given, innovations are Student-t with ``nu`` degrees of freedom
        (scaled to unit variance); otherwise standard normal.

    Returns
    -------
    (returns, sigma2) : tuple of ndarray
        Simulated returns and the true conditional variance path.
    """
    rng = np.random.default_rng(seed)
    total = n + burn
    if nu is None:
        z = rng.standard_normal(total)
    else:
        z = rng.standard_t(nu, total) * np.sqrt((nu - 2.0) / nu)
    sigma2 = np.empty(total)
    eps = np.empty(total)
    sigma2[0] = omega / max(1.0 - alpha - beta - 0.5 * gamma, 1e-6)
    eps[0] = np.sqrt(sigma2[0]) * z[0]
    for t in range(1, total):
        leverage = gamma if eps[t - 1] < 0 else 0.0
        sigma2[t] = omega + (alpha + leverage) * eps[t - 1] ** 2 + beta * sigma2[t - 1]
        eps[t] = np.sqrt(sigma2[t]) * z[t]
    r = mu + eps
    return r[burn:], sigma2[burn:]


def factor_panel(
    n: int,
    n_assets: int = 6,
    n_factors: int = 3,
    seed: int | None = 0,
    factor_vol: float = 0.01,
    idio_vol: float = 0.012,
    start: str = "2015-01-01",
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Simulate asset returns from a linear factor model with known betas.

    r_it = alpha_i + sum_k beta_ik f_kt + e_it

    Returns
    -------
    (asset_returns, factor_returns, true_betas)
        Simulated asset returns (dates x assets), factor returns
        (dates x factors) and the true betas (assets x factors).
    """
    rng = np.random.default_rng(seed)
    dates = pd.bdate_range(start, periods=n)
    assets = [f"SYN{i:02d}" for i in range(n_assets)]
    factors = [f"F{k}" for k in range(n_factors)]

    f = rng.standard_normal((n, n_factors)) * factor_vol
    f[:, 0] += 0.0003  # a small market premium
    betas = rng.uniform(-0.5, 1.5, size=(n_assets, n_factors))
    betas[:, 0] = rng.uniform(0.6, 1.4, size=n_assets)  # market betas near 1
    e = rng.standard_normal((n, n_assets)) * idio_vol
    r = f @ betas.T + e

    asset_returns = pd.DataFrame(r, index=dates, columns=assets)
    asset_returns.index.name, asset_returns.columns.name = "date", "ticker"
    factor_returns = pd.DataFrame(f, index=dates, columns=factors)
    factor_returns.index.name, factor_returns.columns.name = "date", "factor"
    true_betas = pd.DataFrame(betas, index=assets, columns=factors)
    return asset_returns, factor_returns, true_betas


def returns_to_prices(returns: pd.DataFrame, p0: float = 100.0) -> pd.DataFrame:
    """Turn log RETURNS into a PRICES path starting at ``p0`` (one row earlier)."""
    first = returns.index[0] - pd.tseries.offsets.BDay(1)
    padded = pd.concat(
        [pd.DataFrame(0.0, index=[first], columns=returns.columns), returns]
    )
    prices = p0 * np.exp(padded.cumsum())
    prices.index.name, prices.columns.name = "date", "ticker"
    return prices


def synthetic_market(
    n: int = 5 * TRADING_DAYS,
    n_assets: int = 6,
    seed: int = 0,
    start: str = "2019-01-01",
) -> dict:
    """A synthetic market shaped like ``download_prices`` output.

    Asset returns follow a factor model whose factor innovations are
    GARCH(1,1) (so the volatility models have something to find), and the
    "factor ETFs" are noisy observations of the true factors.

    Returns
    -------
    dict with keys
        ``prices``        asset prices (dates x tickers)
        ``factor_prices`` factor-proxy prices (dates x proxies)
        ``true_betas``    the betas used to generate the assets
        ``true_garch``    the GARCH parameters of the market factor
        ``weights``       an example long-only weight vector
    """
    rng = np.random.default_rng(seed)
    dates = pd.bdate_range(start, periods=n)
    assets = [f"SYN{i:02d}" for i in range(n_assets)]
    proxies = ["MKT", "SIZE", "VALUE"]

    true_garch = dict(omega=2e-6, alpha=0.08, beta=0.90, mu=0.0003)
    mkt, _ = garch_series(n, seed=seed, **true_garch)
    size = rng.standard_normal(n) * 0.006
    value = rng.standard_normal(n) * 0.006
    f = np.column_stack([mkt, size, value])

    betas = np.column_stack(
        [
            rng.uniform(0.6, 1.4, n_assets),
            rng.uniform(-0.6, 0.8, n_assets),
            rng.uniform(-0.6, 0.8, n_assets),
        ]
    )
    e = rng.standard_normal((n, n_assets)) * 0.011
    r = f @ betas.T + e

    asset_returns = pd.DataFrame(r, index=dates, columns=assets)
    proxy_returns = pd.DataFrame(
        f + rng.standard_normal(f.shape) * 0.001, index=dates, columns=proxies
    )
    w = rng.uniform(0.5, 1.5, n_assets)
    weights = pd.Series(w / w.sum(), index=assets, name="weight")
    weights.index.name = "ticker"

    return {
        "prices": returns_to_prices(asset_returns),
        "factor_prices": returns_to_prices(proxy_returns),
        "true_betas": pd.DataFrame(betas, index=assets, columns=proxies),
        "true_garch": true_garch,
        "weights": weights,
        "_warning": SYNTHETIC_WARNING,
    }
